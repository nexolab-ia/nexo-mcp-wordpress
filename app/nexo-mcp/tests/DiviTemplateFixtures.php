<?php
/**
 * Escenario común de las pruebas de plantillas del Theme Builder: el Theme Builder en vivo, layouts de cada tipo, plantillas
 * con las metas con que las guarda Divi y las herramientas registradas.
 *
 * @package NexoDev\NexoMCP
 */

declare(strict_types=1);

namespace NexoDev\NexoMCP\Tests;

use NexoDev\NexoMCP\Audit\AuditLogger;
use NexoDev\NexoMCP\Audit\AuditRepository;
use NexoDev\NexoMCP\Authorization\PermissionPolicy;
use NexoDev\NexoMCP\Builders\DiviTemplateStore;
use NexoDev\NexoMCP\MCP\ExtendedAbilityRegistrar;
use NexoDev\NexoMCP\MCP\ToolExecutor;
use NexoDev\NexoMCP\Support\Settings;
use NexoDev\NexoMCP\WooCommerce\ProductGateway;
use NexoDev\NexoMCP\WordPress\AppearanceGateway;
use NexoDev\NexoMCP\WordPress\ContentAdminGateway;
use NexoDev\NexoMCP\WordPress\MaintenanceGateway;
use NexoDev\NexoMCP\WordPress\SeoGateway;

/**
 * Para pruebas de proceso aparte (definen `ET_BUILDER_5_DIR`). La clase que lo usa implementa `DiviTemplateIds`, que
 * tiene las constantes: un trait no puede tenerlas en PHP 8.1.
 */
trait DiviTemplateFixtures {


	/**
	 * @param bool $divi5 Si se define `ET_BUILDER_5_DIR` (Divi 5 activo). Una constante no se puede quitar: sin Divi 5 no se define nunca.
	 */
	protected function prepare_divi_templates( bool $divi5 = true ): void {
		if ( $divi5 && ! defined( 'ET_BUILDER_5_DIR' ) ) {
			define( 'ET_BUILDER_5_DIR', '/tmp/divi5' );
		}
		if ( ! defined( 'ET_BUILDER_VERSION' ) ) {
			define( 'ET_BUILDER_VERSION', '5.19.1' );
		}

		require_once __DIR__ . '/DiviLayoutWpStubs.php';
		require_once __DIR__ . '/DiviLayoutCssStubs.php';
		require_once __DIR__ . '/DiviConditionsWpStubs.php';
		require_once __DIR__ . '/DiviTemplateWpStubs.php';

		\WP_Layout_Stub_State::$css_calls          = array();
		\WP_Layout_Stub_State::$cache_calls        = array();
		\WP_Conditions_Stub_State::$post_types     = array(
			'page' => array( 'public' => true, 'label' => 'Páginas' ),
			'post' => array( 'public' => true, 'label' => 'Entradas' ),
		);
		\WP_Template_Stub_State::$tb_calls         = array();
		$content                                   = '<!-- wp:divi/placeholder --><!-- wp:divi/section --><!-- wp:divi/row --><!-- wp:divi/column -->%s<!-- /wp:divi/column --><!-- /wp:divi/row --><!-- /wp:divi/section --><!-- /wp:divi/placeholder -->';
		$post_content                              = '<!-- wp:divi/post-content {"builderVersion":"5.19.1"} /-->';
		$text                                      = '<!-- wp:divi/text {"builderVersion":"5.19.1"} /-->';

		\WP_Test_State::$posts[100] = new \WP_Post( array( 'ID' => 100, 'post_type' => 'page', 'post_status' => 'publish', 'post_title' => 'Inicio' ) );
		$this->put_layout( self::HEADER, 'header', 'publish', sprintf( $content, $text ) );
		$this->put_layout( self::BODY, 'body', 'publish', sprintf( $content, $post_content ) );
		$this->put_layout( self::BODY_BARE, 'body', 'publish', sprintf( $content, $text ) );
		$this->put_layout( self::FOOTER, 'footer', 'publish', sprintf( $content, $text ) );
		$this->put_layout( self::HEADER_DRAFT, 'header', 'draft', sprintf( $content, $text ) );
	}

	protected function put_layout( int $id, string $slot, string $status, string $content ): void {
		\WP_Test_State::$posts[ $id ] = new \WP_Post( array( 'ID' => $id, 'post_type' => 'et_' . $slot . '_layout', 'post_status' => $status, 'post_title' => 'Layout ' . $id, 'post_content' => $content ) );
	}

	protected function put_live_tb( int $id = self::TB, string $status = 'publish' ): void {
		\WP_Test_State::$posts[ $id ] = new \WP_Post( array( 'ID' => $id, 'post_type' => 'et_theme_builder', 'post_status' => $status, 'post_title' => 'Theme Builder' ) );
	}

	/**
	 * Metas de una plantilla con los valores de Divi (cadenas '1'/'0') y los cambios de la prueba.
	 *
	 * @param array<string, mixed> $over Metas que cambian.
	 * @return array<string, mixed>
	 */
	protected function template_metas( array $over = array() ): array {
		return array_merge(
			array(
				'_et_default'                => '0',
				'_et_enabled'                => '1',
				'_et_autogenerated_title'    => '0',
				'_et_use_on'                 => array(),
				'_et_exclude_from'           => array(),
				'_et_header_layout_id'       => '0',
				'_et_header_layout_enabled'  => '1',
				'_et_body_layout_id'         => '0',
				'_et_body_layout_enabled'    => '1',
				'_et_footer_layout_id'       => '0',
				'_et_footer_layout_enabled'  => '1',
			),
			$over
		);
	}

	/**
	 * Crea una plantilla de Divi y, por omisión, la enlaza al Theme Builder en vivo.
	 *
	 * @param array<string, mixed> $over Metas que cambian.
	 */
	protected function put_template( int $id, string $title, array $over = array(), bool $mapped = true, string $status = 'publish' ): void {
		\WP_Test_State::$posts[ $id ] = new \WP_Post( array( 'ID' => $id, 'post_type' => 'et_template', 'post_status' => $status, 'post_title' => $title ) );

		foreach ( $this->template_metas( $over ) as $key => $value ) {
			if ( is_array( $value ) ) {
				foreach ( $value as $row ) {
					add_post_meta( $id, $key, $row );
				}
				continue;
			}
			update_post_meta( $id, $key, $value );
		}

		if ( $mapped ) {
			add_post_meta( self::TB, '_et_template', (string) $id );
		}
	}

	/**
	 * @param array<string, mixed> $settings Ajustes que cambian.
	 * @return array<string, array<string, mixed>>
	 */
	protected function tools( array $settings = array() ): array {
		\WP_Test_State::$abilities = array();
		$settings                  = $this->settings( array_merge( array( 'read_only' => false, self::SWITCH => true ), $settings ) );

		( new ExtendedAbilityRegistrar(
			$settings,
			new PermissionPolicy( $settings ),
			new ToolExecutor( new AuditLogger( new AuditRepository() ) ),
			new ContentAdminGateway( $settings ),
			new SeoGateway(),
			new AppearanceGateway(),
			new MaintenanceGateway(),
			new ProductGateway( $settings )
		) )->register_abilities();

		return \WP_Test_State::$abilities;
	}

	/**
	 * @param array<string, mixed> $settings Ajustes que cambian.
	 * @return array<string, mixed>
	 */
	protected function tool( string $name, array $settings = array() ): array {
		return $this->tools( $settings )[ 'nexo-mcp/' . $name ];
	}

	protected function snapshot(): string {
		$options = \WP_Test_State::$options;

		unset( $options[ Settings::OPTION_NAME ] );

		return serialize( array( \WP_Test_State::$posts, \WP_Test_State::$meta, \WP_Test_State::$multi_meta, $options ) );
	}

	/**
	 * Filas de `_et_template` del Theme Builder en vivo.
	 *
	 * @return array<int, string>
	 */
	protected function mapping(): array {
		return \WP_Test_State::$multi_meta[ self::TB ]['_et_template'] ?? array();
	}

	/**
	 * Una plantilla nueva válida y NO de sitio entero (inicio, con un cuerpo con `divi/post-content`).
	 *
	 * @param array<string, mixed> $extra Parámetros que cambian.
	 * @return array<string, mixed>
	 */
	protected function new_template( array $extra = array() ): array {
		return array_merge(
			array(
				'title'   => 'Inicio',
				'enabled' => true,
				'use_on'  => array( 'homepage' ),
				'body'    => array( 'layout_id' => self::BODY ),
			),
			$extra
		);
	}

	/**
	 * Metas `_et_*` de una plantilla tal como las lee el conector.
	 *
	 * @return array<string, string|array<int, string>>
	 */
	protected function metas_of( int $id ): array {
		return ( new DiviTemplateStore() )->metas( $id );
	}

	/**
	 * Lo que el conector toca de una plantilla y su mapeo, sin el respaldo: para comprobar que un rechazo no cambia nada.
	 *
	 * @return array<string, mixed>
	 */
	protected function template_state( int $id ): array {
		$post = \WP_Test_State::$posts[ $id ] ?? null;

		return array(
			'title'   => $post instanceof \WP_Post ? $post->post_title : null,
			'status'  => $post instanceof \WP_Post ? $post->post_status : null,
			'metas'   => $this->metas_of( $id ),
			'mapping' => $this->mapping(),
		);
	}
}
